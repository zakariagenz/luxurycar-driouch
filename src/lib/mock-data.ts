/** Seed bookings spanning today ± a few days for admin calendar demo */
function daysFromNow(offset: number, hour = 10): string {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
}

