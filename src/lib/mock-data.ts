export function getDashboardMetrics(bookings: Booking[]): DashboardMetrics {
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const tomorrow = new Date(today);
  tomorrow.setDate(tomorrow.getDate() + 1);

  const isToday = (iso: string) => {
    const d = new Date(iso);
    return d >= today && d < tomorrow;
  };

  return {
    todayPickups: bookings.filter(
      (b) =>
        isToday(b.pickupDatetime) &&
        (b.status === "confirmed" || b.status === "pending")
    ).length,
    todayDropoffs: bookings.filter(
      (b) => isToday(b.dropoffDatetime) && b.status === "picked_up"
    ).length,
    activeRentals: bookings.filter((b) => b.status === "picked_up").length,
    pendingRequests: bookings.filter((b) => b.status === "pending").length,
    monthlyRevenueMad: bookings
      .filter((b) => b.status !== "cancelled")
      .reduce((sum, b) => sum + b.totalMad, 0),
  };
}
